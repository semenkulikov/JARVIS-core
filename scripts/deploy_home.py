"""Run Jarvis from this checkout against an existing JARVIS_HOME (config, models, caches stay).

Writes ``<home>/start_jarvis.vbs`` that sets the JARVIS_* environment and starts
``src/jarvis_supervisor.py`` from this repository, then (with ``--restart``) stops the
running listener through the stop file, starts the new launcher and waits for the log
line ``listening (v...)``. On failure the previous launcher is restored and started.

    python scripts/deploy_home.py --home C:\\Jarvis\\voice --python C:\\Jarvis\\voice\\venv\\Scripts\\pythonw.exe \\
        --env JARVIS_LOG_DIR=C:\\Jarvis\\logs\\voice --restart
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path, PureWindowsPath
from typing import Any, Callable, Dict, Iterable, Optional

REPO = Path(__file__).resolve().parent.parent
ALLOWED_ENV = ("JARVIS_LOG_DIR", "JARVIS_SCREENSHOTS", "JARVIS_CREDENTIAL_PREFIX", "JARVIS_PROJECTS")
LAUNCHER = "start_jarvis.vbs"
BACKUP_SUFFIX = ".pre-repo"


def _vbs(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def render_launcher(home: Path, python: Path, env: Dict[str, str], repo: Path = REPO) -> str:
    """VBScript that starts the repository supervisor with the given environment."""
    lines = [
        "' Generated by scripts/deploy_home.py - runs Jarvis from " + str(repo),
        "Option Explicit",
        "Dim sh, pe",
        'Set sh = CreateObject("WScript.Shell")',
        'Set pe = sh.Environment("Process")',
        "pe(\"JARVIS_HOME\") = " + _vbs(str(home)),
    ]
    for key in sorted(env):
        lines.append("pe(" + _vbs(key) + ") = " + _vbs(env[key]))
    script = PureWindowsPath(str(repo)) / "src" / "jarvis_supervisor.py"  # a Windows launcher on any OS
    lines += [
        "sh.CurrentDirectory = " + _vbs(str(home)),
        "sh.Run " + _vbs('"' + str(python) + '" "' + str(script) + '"') + ", 0, False",
        "",
    ]
    return "\r\n".join(lines)


def parse_env(pairs: Iterable[str]) -> Dict[str, str]:
    env: Dict[str, str] = {}
    for pair in pairs:
        key, sep, value = pair.partition("=")
        if not sep or key not in ALLOWED_ENV:
            raise SystemExit("unsupported --env %r (allowed: %s)" % (pair, ", ".join(ALLOWED_ENV)))
        env[key] = value
    return env


def install_launcher(home: Path, text: str) -> Optional[Path]:
    """Atomically replace the launcher; keep the first pre-repo launcher as backup."""
    target = home / LAUNCHER
    backup = home / (LAUNCHER + BACKUP_SUFFIX)
    if target.exists() and not backup.exists():
        shutil.copy2(target, backup)
    tmp = target.with_suffix(".vbs.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, target)
    return backup if backup.exists() else None


def log_since(log: Path, offset: int) -> str:
    try:
        with open(log, "rb") as f:
            f.seek(min(offset, log.stat().st_size))
            return f.read().decode("utf-8", "replace")
    except OSError:
        return ""


def wait_for(pred: Callable[[], bool], timeout: float, step: float = 0.5) -> bool:
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        if pred():
            return True
        time.sleep(step)
    return pred()


def listener_running(home: Path) -> bool:
    sys.path.insert(0, str(REPO / "src"))
    from jarvis.adapters import runtime as R  # Windows mutex probe; both legacy and repo names
    legacy = "Local\\SemJarvis_" + R.mutex_name(home, "listener").split("_", 1)[1]
    import ctypes
    win: Any = ctypes  # WinDLL exists only on Windows
    k = win.WinDLL("kernel32", use_last_error=True)
    k.OpenMutexW.restype = ctypes.c_void_p
    for name in (R.mutex_name(home, "listener"), legacy, R.mutex_name(home, "supervisor"),
                 legacy.replace("_listener", "_supervisor")):
        h = k.OpenMutexW(0x100000, 0, name)
        if h:
            k.CloseHandle(ctypes.c_void_p(h))
            return True
    return False


def start(home: Path) -> None:
    subprocess.Popen(["wscript.exe", str(home / LAUNCHER)], cwd=str(home))


def restart(home: Path, log: Path, previous: Optional[Path]) -> bool:
    offset = log.stat().st_size if log.exists() else 0
    t0 = time.monotonic()
    (home / "stop").write_text("", encoding="ascii")
    if not wait_for(lambda: not listener_running(home), 30):
        print("listener did not stop; nothing restarted")
        return False
    start(home)
    ok = wait_for(lambda: bool(re.search(r"listening \(v[\d.]+\)", log_since(log, offset))), 90, 1.0)
    text = log_since(log, offset)
    print("downtime_s=%.1f started=%s" % (time.monotonic() - t0, ok))
    if ok and "fatal" not in text:
        return True
    print("ROLLBACK: new launcher failed\n" + text[-2000:])
    if previous is not None:
        (home / "stop").write_text("", encoding="ascii")
        wait_for(lambda: not listener_running(home), 30)
        shutil.copy2(previous, home / LAUNCHER)
        start(home)
    return False


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--home", required=True, type=Path)
    ap.add_argument("--python", required=True, type=Path, help="pythonw.exe of the venv with Jarvis requirements")
    ap.add_argument("--env", action="append", default=[], help="KEY=VALUE, one of " + ", ".join(ALLOWED_ENV))
    ap.add_argument("--restart", action="store_true")
    a = ap.parse_args(argv)
    home, env = a.home.resolve(), parse_env(a.env)
    for need in (home / "config.json", a.python, REPO / "src" / "jarvis_supervisor.py"):
        if not need.exists():
            raise SystemExit("missing: %s" % need)
    previous = install_launcher(home, render_launcher(home, a.python, env))
    print("launcher written: %s (backup: %s)" % (home / LAUNCHER, previous))
    if not a.restart:
        return 0
    log = Path(env.get("JARVIS_LOG_DIR") or home / "logs") / "jarvis_voice.log"
    return 0 if restart(home, log, previous) else 1


if __name__ == "__main__":
    sys.exit(main())
