"""Ports: the interfaces the application needs from the outside world.

Adapters in :mod:`jarvis.adapters` implement them; tests substitute small fakes.
"""
from __future__ import annotations

import os
from typing import Any, Callable, Iterable, Protocol

import numpy as np

Config = dict[str, Any]
Audio = np.ndarray


class SpeechOutput(Protocol):
    """Speaks text; returns False when interrupted or nothing was played."""

    def say(self, text: str, cfg: Config, role: str = "reply", private: bool = False) -> bool: ...


class Synthesizer(Protocol):
    def get_audio(self, text: str, cfg: Config) -> tuple[Audio, int]: ...


class PhraseRecognizer(Protocol):
    """Records one phrase from a capture queue: (text, average confidence, grammar text)."""

    def capture(self, cap: Any, cfg: Config, nospeech_s: float, skip_s: float = 0.0, max_s: float | None = None,
                wake_pause_s: float | None = None) -> tuple[str, float, str]: ...


class ServerTransport(Protocol):
    """Delivers one request to the user's server; replies arrive later through the outbox."""

    def call(self, rid: str, text: str, trigger: str, cfg: Config, test: bool, listener_ack: str = "",
             kind: str = "free", trace: Any = None, extra_payload: dict[str, Any] | None = None) -> bool: ...


class StatusSource(Protocol):
    """Read-only access to the status snapshot the server writes (cache/status.json)."""

    def cached_status(self, field: str | None, cfg: Config) -> tuple[str, str, float | None]: ...

    def load(self) -> dict[str, Any] | None: ...


class DesktopBackend(Protocol):
    """Explicitly requested desktop actions (jarvis.adapters.system on Windows, a fake in tests)."""

    is_fake: bool

    def mute(self, muted: bool) -> None: ...
    def volume(self, value: float) -> None: ...
    def output_volume(self) -> float | None: ...
    def clipboard(self, limit: int) -> tuple[str, bool]: ...
    def window_ocr(self, limit: int) -> tuple[str, bool]: ...
    def screenshot(self, folder: str | os.PathLike[str]) -> str: ...
    def disk(self, drive: str) -> tuple[int, int, str]: ...
    def close_window(self) -> None: ...
    def media(self, play: bool = False) -> None: ...
    def monitor_off(self) -> None: ...
    def lock(self) -> None: ...
    def shutdown(self, seconds: float) -> None: ...
    def shutdown_cancel(self) -> bool: ...
    def playlist(self, url: str) -> None: ...
    def git(self, project: str, which: str, projects_dir: str | None = None) -> str: ...
    def launch(self, target: str) -> None: ...
    def close_apps(self, names: list[str], protect: set[int]) -> int: ...
    def close_windows(self, protect: set[int], keep: Iterable[str] = ()) -> int: ...
    def minimize_all(self) -> None: ...
    def screen_size(self) -> tuple[int, int]: ...
    def open_console(self, command: str, title: str, rect: tuple[int, int, int, int], cwd: str | None = None) -> int: ...
    def end_process(self, pid: int) -> None: ...
    def open_window(self, target: str, place: str | None = None, title: str | None = None) -> int: ...


class TimerStore(Protocol):
    """Persistent timers, reminders and one-shot announcements."""

    def add(self, secs: float, label: str, interval: float = 0, kind: str = "timer", group: str | None = None) -> str: ...
    def cancel(self, kinds: Iterable[str] | None = None) -> int: ...
    def cancel_groups(self, groups: Iterable[str]) -> int: ...
    def pop_fired(self, limit: int = 1, kinds: Iterable[str] | None = None) -> list[dict[str, str]]: ...


class ProjectToolsPort(Protocol):
    def health_reply(self, spoken: str, cfg: Config) -> str: ...
    def start_tests(self, spoken: str, cfg: Config, done: Callable[[Any], None]) -> str: ...


class FoodResultLike(Protocol):
    @property
    def status(self) -> str: ...
    @property
    def spoken(self) -> str: ...
    @property
    def reason(self) -> str: ...


class FoodLog(Protocol):
    def log_text(self, text: str) -> FoodResultLike: ...
    def remaining(self, focus: str = "protein") -> str: ...


class Laptop(Protocol):
    """Read-mostly laptop helpers (jarvis.adapters.laptop): keys, screen, battery, projects."""

    def press(self, vk: int, times: int = 1) -> None: ...
    def monitor_off(self) -> None: ...
    def battery(self) -> tuple[int | None, bool]: ...
    def temperature_c(self) -> int | None: ...
    def find_project(self, spoken: str, latin_fn: Callable[[str], str], projects_dir: str | None = None) -> tuple[str | None, float]: ...
    def recent_repo(self, projects_dir: str | None = None) -> str | None: ...
    def remote_url(self, repo: str) -> str | None: ...
    def cursor_exe(self) -> str | None: ...
